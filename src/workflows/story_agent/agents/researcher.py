    async def research(self, state: StoryState) -> dict:
        """
        Main entry point. Orchestrates the loop:
        Plan -> Execute -> Verify -> (Loop) -> Format
        """
        # Context extraction
        language = state.get("language", "Indonesian")
        theme = state.get("theme", "")
        learning_objectives = state.get("learning_objectives", "")
        target_age = state.get("target_age", "")

        # Check cache first
        cache_key = f"{theme}_{target_age}_{learning_objectives}"
        if cache_key in self._cache:
            logger.info(f"[RISET::MULAI] Saya pernah meneliti topik ini sebelumnya, pakai hasil lama saja supaya lebih cepat.")
            return self._cache[cache_key]

        logger.info(f"[RISET::MULAI] Oke, saya mulai menggali informasi sekarang!")
        if theme:
            logger.info(f"[RISET::MULAI] Topik yang akan saya teliti: {theme}")
        if target_age:
            logger.info(f"[RISET::MULAI] Sasaran usia pembaca: {target_age}")
        if learning_objectives:
            logger.info(f"[RISET::MULAI] Tujuan pembelajaran yang harus saya perhatikan: {learning_objectives}")

        start_time = time.time()
        span_id = None
        if self.langfuse:
            span_id = self.langfuse.start_span(
                name="research_agent",
                input_data={
                    "theme": theme,
                    "target_age": target_age,
                    "learning_objectives": learning_objectives,
                }
            )

        # Container for all gathered info
        gathered_context = []
        all_sources = []

        # --- STEP 1: PLAN ---
        research_feedback = state.get("research_feedback", "")
        existing_notes = state.get("research_notes", "")

        plan = None

        if research_feedback:
            # Re-entry mode: Focus on specific feedback
            logger.warning(f"[RISET::ULANG] Ada catatan yang perlu saya tindak lanjuti: '{research_feedback}'")
            logger.info("[RISET::ULANG] Saya susun ulang rencana riset khusus untuk menutupi celah tersebut...")

            # Create targeted plan manually
            from settings import LanguageConfig
            is_en = LanguageConfig.SYSTEM_LANGUAGE == "en"
            plan = ResearchPlan(questions=[
                ResearchQuestion(
                    question=f"Find details about: {research_feedback}",
                    tool="web_search",
                    reasoning="Critique requested more information" if is_en else "Kritik menyarankan informasi tambahan"
                )
            ])

            # Use existing notes as base context
            if existing_notes:
                gathered_context.append(existing_notes)

        else:
            # Normal mode: Full planning
            plan = await self._plan_research(theme, target_age, learning_objectives)
            logger.info(f"[RISET::MERENCANAKAN] Rencana riset sudah siap, saya akan menjawab {len(plan.questions)} pertanyaan penelitian.")

        # --- STEP 2: EXECUTE ---
        params = {
            "language": language,
            "theme": theme
        }

        # Execute research (New Async Logic)
        context, sources, kg_infos, web_research_details = await self._execute_research(plan, **params)
        gathered_context.extend(context)
        all_sources.extend(sources)

        if not gathered_context:
            logger.warning("[RISET::GAGAL] Waduh, saya tidak berhasil menemukan informasi apapun yang relevan.")
            if self.langfuse and span_id:
                self.langfuse.end_span(span_id=span_id, output_data={"error": "No context found"})
            return {"research_notes": "Research failed.", "research_sources": []}

        # --- STEP 3: SYNTHESIZE & FORMAT ---
        # Generate final output
        result_payload = await self._synthesize_final_output(gathered_context, all_sources, theme, learning_objectives, target_age, language)
        result_payload["web_research_details"] = web_research_details if 'web_research_details' in locals() else []
        result_payload["questions"] = [
            {
                "question": q.question,
                "tool": q.tool,
                "reasoning": q.reasoning
            } for q in plan.questions
        ] if 'plan' in locals() and plan else []

        # Ingestion is now deferred to the 'finalize_ingestion' node at the end of workflow
        # to ensure only sources actually used by the writer/critic are ingested.

        # --- STEP 4: CACHE & FINALIZE ---
        self._cache[cache_key] = result_payload

        elapsed = time.time() - start_time
        logger.success(f"[RISET::SELESAI] Riset selesai dalam {elapsed:.1f} detik! Catatan siap diserahkan ke tim penulis.")

        if self.langfuse and span_id:
            research_notes_text = result_payload.get("research_notes", "")
            output_details = {
                "source_count": len(result_payload.get("research_sources", [])),
                "chars": {"output_chars": len(research_notes_text)},
                "word_count": len(research_notes_text.split()),
                "elapsed_seconds": round(elapsed, 2),
            }

            if 'plan' in locals() and plan:
                output_details["plan_questions"] = [q.question for q in plan.questions]
                output_details["tool_selection"] = [q.tool for q in plan.questions]

            self.langfuse.end_span(
                span_id=span_id,
                output_data=output_details
            )

        return result_payload

