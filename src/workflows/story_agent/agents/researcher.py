    async def _plan_research(self, theme: str, age: str, objectives: str) -> ResearchPlan:
        """Generate research questions and tool assignments"""
        registry = get_registry()
        prompt = registry.get("researcher_planner").format(
            theme=theme,
            target_age=age,
            learning_objectives=objectives,
            user_prompt=theme
        )

        try:
            # --- Google GenAI SDK path (Vertex AI / GenAI API) ---
            if self.client is not None:
                response = await self.client.aio.models.generate_content(
                    model=self.model_name,
                    contents=prompt,
                    config=GenerateContentConfig(
                        response_mime_type="application/json",
                        response_schema=ResearchPlan,
                        temperature=0.2
                    )
                )
                plan = response.parsed

            # --- LangChain fallback for non-Google providers ---
            else:
                from langchain_core.messages import HumanMessage, SystemMessage  # noqa: PLC0415
                structured_llm = self._lc_llm.with_structured_output(ResearchPlan)
                plan = await structured_llm.ainvoke([HumanMessage(content=prompt)])
                # Untuk provider non-Google selain OpenRouter: web_search tidak tersedia,
                # tapi LightRAG tetap selalu aktif via _execute_research.
                if not self._is_openrouter:
                    for q in plan.questions:
                        if q.tool == "web_search":
                            q.tool = "lightrag"
                            q.reasoning = "Web search unavailable for non-Google/OpenRouter provider; using LightRAG"

            # Log generation
            if hasattr(self, 'langfuse') and self.langfuse:
                self.langfuse.log_generation(
                    name="research_planning",
                    model=self.model_name,
                    input_text=ResearchPlanningInput(
                        model=self.model_name,
                        system_prompt=prompt,
                        theme=theme,
                        target_age=age,
                        learning_objectives=objectives,
                    ).model_dump_json(indent=2),
                    output_text=plan.model_dump_json(indent=2),
                    metadata={"question_count": len(plan.questions)}
                )

            for q in plan.questions:
                logger.debug(f"[RISET::MERENCANAKAN]   [{q.tool.upper()}] {q.question}")
            return plan
        except Exception as e:
            logger.error(f"[RISET::GALAT] Gagal menyusun rencana riset: {e}, menggunakan pertanyaan cadangan.")

            from settings import LanguageConfig  # noqa: PLC0415
            sys_lang = LanguageConfig.SYSTEM_LANGUAGE
            fallback_msg = f"Facts about {theme}" if sys_lang == "en" else f"Fakta tentang {theme}"

            # Fallback plan
            return ResearchPlan(questions=[
                ResearchQuestion(question=fallback_msg, tool="web_search", reasoning="Fallback")
            ])

    async def _execute_research(self, plan: ResearchPlan, language: str, theme: str) -> tuple[List[str], List[dict], List[str], List[dict]]:
        """Execute the plan in parallel with detailed tracking"""
        tasks = []
        task_meta = [] # Store metadata for each task: (type, question)

        if INTEGRATIONS_AVAILABLE:
            from ..integrations.lightrag_client import get_lightrag_client
            self.lightrag = get_lightrag_client(language)

        for item in plan.questions:
            tool_to_use = item.tool

            # LightRAG tidak tersedia → paksa web_search jika memang direncanakan pakai LightRAG
            if (tool_to_use == "lightrag" or tool_to_use == "both") and not self.lightrag:
                logger.warning(
                    f"[RISET::MENGALIHKAN] Basis pengetahuan tidak tersedia, "
                    "saya alihkan pertanyaan ini ke pencarian web."
                )
                if tool_to_use == "lightrag":
                    tool_to_use = "web_search"

            # Web search (sesuai rencana atau "both")
            if tool_to_use in ["web_search", "both"]:
                tasks.append(self._search_web(item.question, language, theme))
                task_meta.append({"type": "web", "question": item.question})

            # LightRAG — selalu aktif jika tersedia, tanpa bergantung pada keputusan planner
            if self.lightrag:
                tasks.append(self._query_kg(item.question))
                task_meta.append({"type": "kg", "question": item.question})

        results = await asyncio.gather(*tasks, return_exceptions=True)

        context_chunks = []
        sources = []
        kg_infos = [] # Track KG findings for consolidated span
        web_research_details = [] # detailed Q&A for web search

        for i, res in enumerate(results):
            meta = task_meta[i]
            question = meta["question"]

            if isinstance(res, tuple) and len(res) == 2: # Web result (text, sources)
                text, src = res
                if text:
                    context_chunks.append(text)
                    # Capture web search details
                    if meta["type"] == "web":
                        web_research_details.append({
                            "question": question,
                            "answer": text,
                            "source_uris": [s.get("uri") for s in src] if src else []
                        })
                if src: sources.extend(src)

            elif isinstance(res, str) and res: # KG result
                context_chunks.append(res)
                kg_infos.append(res)

        return context_chunks, sources, kg_infos, web_research_details

    async def _search_web(self, query: str, language: str, theme: str) -> tuple[str, List[dict]]:
        """Dispatch web search to the appropriate provider implementation."""
        if self._is_openrouter or self._openrouter_api_key:
            return await self._search_web_openrouter(query, language, theme)
            
        if self.client is None:
            # Fallback to SearxNG local metasearch engine
            return await self._search_web_searxng(query, language, theme)
            
        return await self._search_web_google(query, language, theme)

    async def _search_web_searxng(self, query: str, language: str, theme: str) -> tuple[str, List[dict]]:
        """Perform web search via local SearxNG instance."""
        logger.info(f"[RISET::MENCARI] Sedang menelusuri web via SearxNG untuk: {query}")
        
        try:
            searxng_url = os.getenv("SEARXNG_URL", "http://localhost:8081").rstrip("/")
            search_endpoint = f"{searxng_url}/search"
            params = {
                "q": query,
                "format": "json",
                "language": "id-ID"
            }
            async with httpx.AsyncClient(timeout=30.0, follow_redirects=True) as client:
                resp = await client.get(search_endpoint, params=params)
                resp.raise_for_status()
                data = resp.json()
            
            text_chunks = []
            sources = []
            
            # Ambil hingga 5 hasil teratas
            for r in data.get("results", [])[:5]:
                snippet = r.get("content", "")
                title = r.get("title", "")
                href = r.get("url", "")
                if snippet and href:
                    text_chunks.append(f"Title: {title}\nSnippet: {snippet}")
                    sources.append({"title": title, "uri": href, "snippet": snippet})
            
            web_text = "\n\n".join(text_chunks)
            return web_text, sources
            
        except Exception as e:
            logger.warning(f"[RISET::SEARXNG_FAIL] Pencarian SearxNG gagal: {e}")
            return "", []

    async def _search_web_openrouter(self, query: str, language: str, theme: str) -> tuple[str, List[dict]]:
        """Perform web search via OpenRouter Web Plugin.

        Calls OpenRouter API with ``plugins: [{"id": "web"}]`` which triggers
        real-time web retrieval on any capable model.  Sources are extracted
        from the ``annotations`` field returned by OpenRouter.
        """
        logger.info(f"[RISET::MENCARI] Sedang menelusuri web untuk: {query}")
        start_time = time.time()

        registry = get_registry()
        prompt = registry.get("researcher_web").format(
            query=query,
            target_age="8-10",
            extraction_guidance="informasi faktual murni"
        )

        headers = {
            "Authorization": f"Bearer {self._openrouter_api_key}",
            "Content-Type": "application/json",
        }
        site_url = os.getenv("OPENROUTER_SITE_URL") or ""
        app_name = os.getenv("OPENROUTER_APP_NAME") or "Story-Based Learning AI"
        if site_url:
            headers["HTTP-Referer"] = site_url
        if app_name:
            headers["X-Title"] = app_name

        # If using Ollama/DeepSeek as main provider, use a fast/cheap OR model strictly for searching
        search_model = self.model_name if self._is_openrouter else "google/gemini-2.5-flash"

        payload = {
            "model": search_model,
            "messages": [{"role": "user", "content": prompt}],
            "plugins": [{"id": "web"}],
            "temperature": 0.3,
        }

        try:
            async with httpx.AsyncClient(timeout=60.0) as client:
                resp = await client.post(
                    f"{self._openrouter_base_url}/chat/completions",
                    headers=headers,
                    json=payload,
                )
                resp.raise_for_status()
                data = resp.json()

            elapsed = time.time() - start_time
            choice = data["choices"][0]["message"]
            text = choice.get("content") or ""

            # Parse citations from annotations field
            sources: List[dict] = []
            for ann in choice.get("annotations") or []:
                if ann.get("type") == "url_citation":
                    cit = ann.get("url_citation", {})
                    sources.append({
                        "uri": cit.get("url", ""),
                        "title": cit.get("title", ""),
                        "snippet": cit.get("content", "")[:300],
                    })

            if sources:
                logger.success(f"[RISET::MENEMUKAN] Dapat {len(sources)} sumber dari web dalam {elapsed:.2f} detik!")
            else:
                logger.info(f"[RISET::MENCARI] Pencarian selesai, tidak ada sumber eksplisit yang dikembalikan ({elapsed:.2f}s).")

            return text, sources

        except httpx.HTTPStatusError as e:
            logger.error(f"[RISET::GALAT] Pencarian web via OpenRouter gagal (HTTP {e.response.status_code}): {e.response.text[:200]}")
            return "", []
        except Exception as e:
            logger.error(f"[RISET::GALAT] Pencarian web via OpenRouter error: {e}")
            return "", []

    async def _search_web_google(self, query: str, language: str, theme: str) -> tuple[str, List[dict]]:
        """Perform web search via Google Search grounding (Google provider only)."""

        logger.info(f"[RISET::MENCARI] Sedang menelusuri internet untuk: {query}")
        start_time = time.time()

        try:
            # Async call
            registry = get_registry()
            # The context extraction is updated to pass 'extraction_guidance' from the planner,
            # but for backward compatibility in fallback we just pass an empty string
            prompt = registry.get("researcher_web").format(
                query=query,
                target_age="8-10", # generic fallback
                extraction_guidance="informasi factual murni"
            )

            response = await self.client.aio.models.generate_content(
                model=self.model_name,
                contents=prompt,
                config=GenerateContentConfig(
                    tools=[Tool(google_search=GoogleSearch())],
                )
            )

            elapsed = time.time() - start_time
            text = response.text
            sources = self._extract_sources(response)

            if sources:
                logger.success(f"[RISET::MENEMUKAN] Berhasil mengumpulkan {len(sources)} sumber dalam {elapsed:.2f} detik!")
            else:
                logger.info(f"[RISET::MENCARI] Pencarian selesai, tidak ada sumber eksplisit yang dikembalikan ({elapsed:.2f}s).")

            return text, sources

        except Exception as e:
            logger.error(f"[RISET::GALAT] Pencarian web via Google gagal: {e}")
            return "", []

    async def _query_kg(self, query: str) -> str:
        """Query LightRAG"""
        logger.info(f"[RISET::MENGINGAT] Menggali dari basis pengetahuan: {query}")
        start_t = time.time()

        try:
            res = await self.lightrag.query(query, mode="hybrid")
            elapsed = time.time() - start_t
            if res.response and "No relevant context" not in res.response:
                logger.success(f"[RISET::MENGINGAT] Ada! Menemukan {len(res.response)} karakter informasi relevan dari basis pengetahuan ({elapsed:.2f}s).")
                return f"## KG Context ({query}):\n{res.response}"

            logger.info(f"[RISET::MENGINGAT] Tidak ada informasi relevan di basis pengetahuan untuk pertanyaan ini ({elapsed:.2f}s).")
            return ""
        except Exception as e:
            url = self.lightrag.api_url if self.lightrag else "N/A"
            logger.error(f"[RISET::GALAT] Gagal mengakses basis pengetahuan ({url}): {type(e).__name__}: {e}")
            return ""


    async def _synthesize_final_output(self, context: List[str], sources: List[dict], theme: str, objectives: str, age: str, language: str) -> dict:
        """Concatenate raw research materials directly without LLM synthesis for maximum detail"""
        combined_text = "\n\n".join(context)

        sys_lang = LanguageConfig.SYSTEM_LANGUAGE

        # Prepend sources to the raw notes (Top visibility)
        source_header = ""
        if sources:
            if sys_lang == "en":
                source_header = "## RESEARCH SOURCES (Used for Ingestion):\n" + "\n".join([f"- {s['title']}: {s['uri']}" for s in sources]) + "\n\n---\n\n"
            else:
                source_header = "## SUMBER RISET (Digunakan untuk Ingest):\n" + "\n".join([f"- {s['title']}: {s['uri']}" for s in sources]) + "\n\n---\n\n"

        final_notes = f"{source_header}## RAW RESEARCH CONTENT:\n\n{combined_text}"

        logger.info(f"[RISET::MERANGKUM] Menyusun {len(context)} temuan penelitian menjadi catatan terpadu ({len(final_notes)} karakter).")

        return {
            "research_notes": final_notes,
            "research_sources": sources,
            "retrieved_contexts": context,
            "current_stage": "planning",
            "messages": [{"role": "researcher", "content": f"Found {len(sources)} sources and {len(combined_text)} chars of raw material."}]
        }

    def _extract_sources(self, response) -> List[dict]:
        """Helper to extract sources from GenAI response"""
        sources = []
        if hasattr(response, 'candidates') and response.candidates:
            candidate = response.candidates[0]
            if hasattr(candidate, 'grounding_metadata') and candidate.grounding_metadata:
                metadata = candidate.grounding_metadata
                if hasattr(metadata, 'grounding_chunks') and metadata.grounding_chunks:
                    for chunk in metadata.grounding_chunks:
                        if hasattr(chunk, 'web') and chunk.web:
                            sources.append({
                                "title": chunk.web.title,
                                "uri": chunk.web.uri
                            })
        return sources

    async def _resolve_url(self, url: str) -> str:
        """Resolve redirect URLs (like vertexaisearch) to final destination"""
        if "vertexaisearch" not in url and "google.com" not in url:
            return url

        try:
             async with httpx.AsyncClient(timeout=10.0, follow_redirects=True) as client:
                resp = await client.head(url)
                final_url = str(resp.url)
                if final_url != url:
                    logger.debug(f"[RISET::RESOLVE] Resolved {url[:50]}... -> {final_url}")
                return final_url
        except Exception as e:
            logger.debug(f"[RISET::RESOLVE_FAIL] Could not resolve {url}: {e}")
            return url

    async def _ingest_web_to_kg(self, sources: List[dict], query: str):
        """
        Ingest web sources individually.
        Checks existence by link before inserting to avoid duplicates.
        """
        # Deduplicate to_ingest list by URI first to prevent redundant processing within the same task
        unique_sources = []
        seen_uris = set()
        duplicate_count = 0
        for s in sources:
            uri = s.get("uri")
            if not uri: continue
            if uri in seen_uris:
                duplicate_count += 1
                continue
            seen_uris.add(uri)
            unique_sources.append(s)

        if duplicate_count > 0:
            logger.info(f"[RISET::DEDUPLIKASI] Mengabaikan {duplicate_count} tautan yang sudah pernah diproses dalam sesi ini.")

        logger.info(f"[RISET::MENYIMPAN] Memproses {len(unique_sources)} tautan unik ke basis pengetahuan...")

        for source in unique_sources:
            original_uri = source.get("uri")
            if not original_uri: continue

            # Resolve URL if it's a redirect
            uri = await self._resolve_url(original_uri)

            # Skip ONLY technical Grounding UI redirects from Vertex AI
            if "vertexaisearch" in uri:
                logger.debug(f"[RISET::SKIP] Melewati tautan internal Vertex AI Grounding: {uri}")
                continue

            # Simplified ID as requested: "web_{link}" (sanitized for safety)
            # We replace non-alphanumeric chars with _ to avoid filesystem/API issues
            safe_uri = re.sub(r'[^a-zA-Z0-9]', '_', uri)
            # Limit length to avoid issues
            if len(safe_uri) > 100: safe_uri = safe_uri[:100]

            file_source = f"web_{safe_uri}"

            # Check existence first
            try:
                exists = await self.lightrag.get_document_status(file_source)
                if exists:
                    logger.info(f"[RISET::SUDAH_ADA] Sumber ini sudah tersimpan di basis pengetahuan, saya lewati: {uri}")
                    continue
            except Exception as e:
                pass

            # Fetch content
            try:
                content_text = await self._fetch_url_content(uri)
                # Increase threshold to 800 based on user feedback
                if not content_text or len(content_text) < 800:
                    reason = "kosong" if not content_text else f"terlalu pendek ({len(content_text)} karakter, minimal 800)"
                    logger.warning(f"[RISET::MELEWATI] Konten dari {uri} {reason}, saya lewati.")
                    continue

                # Insert
                await self.lightrag.insert_text(content_text, file_source=file_source)

                # SIMPAN_BARU only on success
                logger.success(f"[RISET::TERSIMPAN] Berhasil menyimpan ke basis pengetahuan: {file_source} ({len(content_text)} karakter).")

            except Exception as e:
                 logger.warning(f"[RISET::GAGAL_SIMPAN] Tidak bisa memproses {uri}: {e}")

    async def _fetch_url_content(self, url: str) -> str:
        """Fetch content from URL with robust metadata extraction and targeted cleaning"""
        try:
            # Use a modern User-Agent
            headers = {
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
            }
            async with httpx.AsyncClient(timeout=15.0, follow_redirects=True, headers=headers) as client:
                response = await client.get(url)
                response.raise_for_status()

                html = response.text
                if not html: return ""

                # 1. Robust YouTube Extraction
                if "youtube.com" in url or "youtu.be" in url:
                    title = ""
                    title_patterns = [
                        r'<meta name="title" content="([^"]+)">',
                        r'<meta property="og:title" content="([^"]+)">',
                        r'<title>([^<]+)</title>',
                        r'<meta name=\'title\' content=\'([^\']+)\'>'
                    ]
                    for pattern in title_patterns:
                        match = re.search(pattern, html, re.I)
                        if match:
                            title = match.group(1).strip()
                            break

                    desc = ""
                    desc_patterns = [
                        r'<meta name="description" content="([^"]+)">',
                        r'<meta property="og:description" content="([^"]+)">',
                        r'<meta property="twitter:description" content="([^"]+)">',
                        r'<meta name=\'description\' content=\'([^\']+)\'>',
                        r'shortDescription":"(.*?)"' # YT internal JSON
                    ]
                    for pattern in desc_patterns:
                        match = re.search(pattern, html, re.I)
                        if match:
                            raw_desc = match.group(1)
                            if '"' in pattern:
                                try:
                                    desc = raw_desc.encode().decode('unicode_escape')
                                except:
                                    desc = raw_desc
                            else:
                                desc = raw_desc
                            break

                    title = title or "YouTube Video"
                    combined = f"YOUTUBE VIDEO: {title}\n\nSUMMARY:\n{desc}"
                    return re.sub(r'\s+', ' ', combined).strip()

                # 2. General Site Targeted Extraction
                # Try to isolate main content if possible (article, main tags)
                article_match = re.search(r'<(article|main)[^>]*>(.*?)</\1>', html, flags=re.DOTALL | re.IGNORECASE)
                if article_match:
                    content_html = article_match.group(2)
                else:
                    content_html = html

                # Targeted Cleaning (avoid removing content tags like div/p)
                # Remove scripts and styles
                content_html = re.sub(r'<(script|style)[^>]*>.*?</\1>', ' ', content_html, flags=re.DOTALL | re.IGNORECASE)
                # Remove boilerplate headers/nav but NOT content sections
                content_html = re.sub(r'<(nav|aside)[^>]*>.*?</\1>', ' ', content_html, flags=re.DOTALL | re.IGNORECASE)
                # Remove comments
                content_html = re.sub(r'<!--.*?-->', ' ', content_html, flags=re.DOTALL)

                # Strip tags
                text = re.sub(r'<[^>]+>', ' ', content_html)
                # Collapse whitespace
                text = re.sub(r'\s+', ' ', text).strip()

                return text[:50000]
        except Exception as e:
            logger.warning(f"[FETCH_ERR] Failed {url}: {e}")
            return ""

    async def finalize_ingestion(self, state: StoryState) -> dict:
        """
        Final synchronization node. Ingests sources into LightRAG
        if they were actually used in the final story or draft.
        """
        if INTEGRATIONS_AVAILABLE:
            from ..integrations.lightrag_client import get_lightrag_client
            # Finalize ingestion occurs after everything, so we assume theme/age dictates language
            language = state.get("language", "id")
            self.lightrag = get_lightrag_client(language)

        if not self.lightrag:
            return {}

        sources = state.get("research_sources", [])
        if not sources:
            return {}

        final_story = state.get("final_story") or state.get("draft_content") or ""
        used_uris = state.get("used_sources") or []
        theme = state.get("theme", "unknown_topic")

        # Check config
        is_selective = LightRAGConfig.SELECTIVE_INGESTION
        logger.info(f"[RISET::INGEST] Finalizing ingestion (Selective={is_selective}, ExplicitUsed={len(used_uris)})")

        to_ingest = []
        if not is_selective:
            to_ingest = sources
        else:
            # Match against explicit used sources from writer pydantic output
            used_uris_lower = [u.lower() for u in used_uris if u]

            # Match against final story content
            story_lower = final_story.lower()

            for src in sources:
                title = src.get("title", "").lower()
                uri = src.get("uri", "").lower()

                # 1. Check if explicitly in used_uris
                if uri and any(uri in u or u in uri for u in used_uris_lower):
                    to_ingest.append(src)
                    continue

                # 2. Heuristic: title mentioned (more than just generic words)
                if title and len(title) > 5 and title in story_lower:
                    to_ingest.append(src)
                    continue

                # 3. Heuristic: URI domain or unique slug mentioned
                if uri:
                    try:
                        # Try to find domain
                        parts = uri.split("//")[-1].split("/")
                        domain = parts[0]
                        if domain and len(domain) > 4 and domain in story_lower:
                            to_ingest.append(src)
                            continue

                        # Try slug (last part of URL)
                        if len(parts) > 1:
                            slug = parts[-1].split("?")[0].replace("-", " ").replace("_", " ")
                            if len(slug) > 8 and slug.lower() in story_lower:
                                to_ingest.append(src)
                                continue
                    except:
                        pass

        if to_ingest:
            logger.info(f"[RISET::INGEST] Found {len(to_ingest)}/{len(sources)} used sources to ingest into LightRAG")
            # Fire and forget ingestion task
            asyncio.create_task(self._safe_ingest(to_ingest, theme))

        return {}

