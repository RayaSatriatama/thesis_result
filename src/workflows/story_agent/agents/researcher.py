# --- Pydantic Models for Internal Logic ---

class ResearchQuestion(BaseModel):
    """A specific question to research"""
    question: str = Field(..., description="The specific question to answer")
    tool: Literal["web_search", "lightrag", "both"] = Field(..., description="Best tool for this question")
    reasoning: str = Field(..., description="Why this tool was chosen" if LanguageConfig.SYSTEM_LANGUAGE == "en" else "Mengapa alat ini dipilih")

class ResearchPlan(BaseModel):
    """The research plan generated by the planner"""
    questions: List[ResearchQuestion] = Field(..., description="List of research questions")


class ResearchOutput(BaseModel):
    """Final output to the state (Backward Compatibility)"""
    key_facts: List[str] = Field(..., description="Key verified facts from the sources")
    age_appropriate_lessons: List[str] = Field(..., description="Values and lessons suitable for the target age")
    real_world_examples: List[str] = Field(..., description="Concrete examples from real world")
    cultural_context: List[str] = Field(..., description="Locally relevant cultural references/folklore")
